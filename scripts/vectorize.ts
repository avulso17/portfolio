import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'
import { Potrace, PotraceOptions } from 'potrace'

const REPO_ROOT = path.resolve(__dirname, '..')
const MAX_DIMENSION = 800
const PADDING_RATIO = 0.04

const DEFAULT_POTRACE_OPTIONS: PotraceOptions = {
  threshold: 128,
  blackOnWhite: false,
  turdSize: 24,
  optTolerance: 0.4,
  alphaMax: 1,
}

async function preprocess(inputPath: string) {
  const resized = await sharp(inputPath)
    .resize({
      width: MAX_DIMENSION,
      height: MAX_DIMENSION,
      fit: 'inside',
    })
    .toBuffer()

  const { data: trimmed, info: trimmedInfo } = await sharp(resized)
    .trim()
    .toBuffer({ resolveWithObject: true })

  const { width: tw, height: th } = trimmedInfo
  const side = Math.max(tw, th)
  const pad = Math.round(side * PADDING_RATIO)
  const squareSide = side + pad * 2

  const left = Math.floor((squareSide - tw) / 2)
  const right = squareSide - tw - left
  const top = Math.floor((squareSide - th) / 2)
  const bottom = squareSide - th - top

  const buffer = await sharp(trimmed)
    .extend({
      top,
      bottom,
      left,
      right,
      background: { r: 0, g: 0, b: 0, alpha: 1 },
    })
    .grayscale()
    .threshold(128)
    .png()
    .toBuffer()

  return { buffer, size: squareSide }
}

function vectorize(buffer: Buffer, options: PotraceOptions): Promise<string> {
  return new Promise((resolve, reject) => {
    const trace = new Potrace(options)
    trace.loadImage(buffer, function (this: Potrace, err: Error | null) {
      if (err) {
        reject(err)
        return
      }
      const tag = this.getPathTag()
      const match = tag.match(/d="([^"]+)"/)
      if (!match) {
        reject(new Error('potrace produced a path tag with no d attribute'))
        return
      }
      resolve(match[1])
    })
  })
}

async function trace(name: string, inputPath: string, options: PotraceOptions) {
  const { buffer, size } = await preprocess(inputPath)
  const d = await vectorize(buffer, options)
  const kb = (Buffer.byteLength(d) / 1024).toFixed(1)
  console.log(`${name}: viewBox 0 0 ${size} ${size}, d = ${kb} KB`)
  return { viewBox: `0 0 ${size} ${size}`, d }
}

async function run() {
  const nohalo = await trace(
    'FM_PLAIN',
    path.join(REPO_ROOT, 'art/mark/fm-nohalo.png'),
    DEFAULT_POTRACE_OPTIONS
  )

  let halo = await trace(
    'FM_HALO',
    path.join(REPO_ROOT, 'art/mark/fm-halo.png'),
    DEFAULT_POTRACE_OPTIONS
  )

  const haloKb = Buffer.byteLength(halo.d) / 1024
  if (haloKb > 150) {
    console.log(
      `FM_HALO exceeded 150 KB (${haloKb.toFixed(1)} KB), retracing with looser tolerance`
    )
    halo = await trace(
      'FM_HALO',
      path.join(REPO_ROOT, 'art/mark/fm-halo.png'),
      { ...DEFAULT_POTRACE_OPTIONS, turdSize: 40, optTolerance: 0.8 }
    )
  }

  const outPath = path.join(
    REPO_ROOT,
    'src/assets/ex-libris/monogram.generated.ts'
  )

  const contents = `// Generated by \`pnpm vectorize\`. Do not edit by hand.
export type Monogram = { viewBox: string; d: string }

export const FM_HALO: Monogram = ${JSON.stringify(halo, null, 2)}

export const FM_PLAIN: Monogram = ${JSON.stringify(nohalo, null, 2)}
`

  await mkdir(path.dirname(outPath), { recursive: true })
  await writeFile(outPath, contents)
  console.log(`wrote ${path.relative(REPO_ROOT, outPath)}`)
}

run().catch((err) => {
  console.error(err)
  process.exit(1)
})
